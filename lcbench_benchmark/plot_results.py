"""Plot anytime performance curves from benchmark CSV outputs.

Input: `all_results.csv` generated by benchmark_runner.py.
Output: publication-ready PNG/PDF with mean +/- std across seeds.
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Dict, List, Tuple

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import seaborn as sns


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Generate anytime performance plots from benchmark logs"
    )
    parser.add_argument(
        "--input-csv",
        type=str,
        required=True,
        help="Path to all_results.csv",
    )
    parser.add_argument(
        "--output-dir",
        type=str,
        default="benchmark_outputs/plots",
        help="Directory where figures and aggregated curves are written",
    )
    parser.add_argument(
        "--title",
        type=str,
        default="Anytime Performance on YAHPO",
        help="Plot title",
    )
    parser.add_argument(
        "--n-grid",
        type=int,
        default=300,
        help="Number of x-axis grid points for trajectory interpolation",
    )
    return parser.parse_args()


def make_common_cost_grid(cost_values: np.ndarray, n_grid: int) -> np.ndarray:
    """Build common x-grid for averaging trajectories across seeds."""

    positive = cost_values[cost_values > 0]
    if positive.size == 0:
        raise ValueError("No positive cumulative cost values found in input data")

    c_min = float(np.min(positive))
    c_max = float(np.max(positive))

    if c_max / c_min >= 100:
        return np.logspace(np.log10(c_min), np.log10(c_max), num=n_grid)
    return np.linspace(c_min, c_max, num=n_grid)


def step_interpolate(
    x: np.ndarray,
    y: np.ndarray,
    x_grid: np.ndarray,
) -> np.ndarray:
    """Right-continuous interpolation for best-so-far trajectories.

    We use a step function, since best-so-far should remain constant between
    observation points.
    """

    order = np.argsort(x)
    x_sorted = x[order]
    y_sorted = y[order]

    # Ensure best-so-far monotonicity in case logs were externally modified.
    y_sorted = np.minimum.accumulate(y_sorted)

    idx = np.searchsorted(x_sorted, x_grid, side="right") - 1
    out = np.full_like(x_grid, fill_value=np.nan, dtype=float)

    valid = idx >= 0
    out[valid] = y_sorted[idx[valid]]

    # Before first observation, use first measured performance.
    out[~valid] = y_sorted[0]
    return out


def aggregate_anytime_curves(
    df: pd.DataFrame,
    n_grid: int,
) -> Tuple[pd.DataFrame, np.ndarray]:
    """Aggregate per-seed trajectories into mean/std curves per algorithm."""

    x_grid = make_common_cost_grid(df["cumulative_cost"].to_numpy(), n_grid=n_grid)

    trajectories: Dict[str, List[np.ndarray]] = {}

    grouped = df.groupby(["algorithm", "seed"], sort=True)
    for (algorithm, _seed), run_df in grouped:
        x = run_df["cumulative_cost"].to_numpy(dtype=float)
        y = run_df["best_validation_error"].to_numpy(dtype=float)
        curve = step_interpolate(x=x, y=y, x_grid=x_grid)
        trajectories.setdefault(algorithm, []).append(curve)

    rows = []
    for algorithm, curves in trajectories.items():
        stacked = np.vstack(curves)
        mean = np.mean(stacked, axis=0)
        std = np.std(stacked, axis=0)

        for x_val, mean_val, std_val in zip(x_grid, mean, std):
            rows.append(
                {
                    "algorithm": algorithm,
                    "cumulative_cost": float(x_val),
                    "mean_best_validation_error": float(mean_val),
                    "std_best_validation_error": float(std_val),
                }
            )

    return pd.DataFrame(rows), x_grid


def plot_anytime_curves(
    agg_df: pd.DataFrame,
    x_grid: np.ndarray,
    title: str,
    output_dir: Path,
) -> None:
    """Render and save publication-ready anytime performance figure."""

    output_dir.mkdir(parents=True, exist_ok=True)

    sns.set_theme(style="whitegrid", context="talk")
    fig, ax = plt.subplots(figsize=(11, 7), dpi=160)

    # High-contrast palette for print and presentation readability.
    palette = {
        "random_search": "#1f77b4",  # blue
        "asha": "#d62728",  # red
        "bohb": "#2ca02c",  # green
        "dehb": "#ff7f0e",  # orange
        "hagfish": "#000000",  # black
    }
    markers = {
        "random_search": "o",
        "asha": "s",
        "bohb": "^",
        "dehb": "D",
        "hagfish": "X",
    }

    algorithms = sorted(agg_df["algorithm"].unique())

    for algorithm in algorithms:
        sub = agg_df[agg_df["algorithm"] == algorithm].sort_values(
            "cumulative_cost"
        )

        color = palette.get(algorithm, "#7f7f7f")
        marker = markers.get(algorithm, "o")

        x = sub["cumulative_cost"].to_numpy(dtype=float)
        mean = sub["mean_best_validation_error"].to_numpy(dtype=float)
        std = sub["std_best_validation_error"].to_numpy(dtype=float)

        ax.plot(
            x,
            mean,
            label=algorithm,
            color=color,
            linewidth=2.5,
            marker=marker,
            markevery=max(1, len(x_grid) // 16),
            markersize=6,
        )
        ax.fill_between(
            x,
            mean - std,
            mean + std,
            color=color,
            alpha=0.16,
            linewidth=0,
        )

    positive = x_grid[x_grid > 0]
    if positive.size > 0 and positive.max() / positive.min() >= 100:
        ax.set_xscale("log")

    ax.set_xlabel("Cumulative Simulated Cost")
    ax.set_ylabel("Best Validation Error (lower is better)")
    ax.set_title(title)
    ax.legend(loc="best", frameon=True)

    fig.tight_layout()
    fig.savefig(output_dir / "anytime_performance.png", bbox_inches="tight")
    fig.savefig(output_dir / "anytime_performance.pdf", bbox_inches="tight")
    plt.close(fig)


def main() -> None:
    args = parse_args()

    input_csv = Path(args.input_csv)
    if not input_csv.exists():
        raise FileNotFoundError(f"Input CSV not found: {input_csv}")

    df = pd.read_csv(input_csv)

    required_cols = {
        "algorithm",
        "seed",
        "cumulative_cost",
        "best_validation_error",
    }
    missing = sorted(required_cols - set(df.columns))
    if missing:
        raise ValueError(
            f"Missing required columns in input CSV: {missing}. "
            "Use all_results.csv from benchmark_runner.py"
        )

    agg_df, x_grid = aggregate_anytime_curves(df=df, n_grid=args.n_grid)

    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    agg_df.to_csv(output_dir / "aggregated_anytime_curves.csv", index=False)

    plot_anytime_curves(
        agg_df=agg_df,
        x_grid=x_grid,
        title=args.title,
        output_dir=output_dir,
    )


if __name__ == "__main__":
    main()
